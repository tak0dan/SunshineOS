def fake_executor(commands: dict[str, tuple[int, str, str]]) -> FakeExecute:
    """Build an executor that reports unlisted commands as unavailable."""
    def execute(command: str) -> tuple[int, str, str]:
        return commands.get(command, (127, "", f"fake root has no output for {command!r}"))

    return execute


def add_old_sunshine(root: str, commands: dict[str, tuple[int, str, str]]) -> None:
    """Turn the clean Arch fixture into a partially installed old Sunshine system."""
    write_file(root, "/etc/sunshine/schema.json", '{"id": "core", "schema": 2}\n')
    write_file(root, "/etc/sunshine/components/audio.json", '{"id": "audio", "schema": 1}\n')
    write_file(root, "/var/lib/sunshine/state.json", '{"schema": 2, "journal": []}\n')

    # A GRUB firmware entry plus the existing config raises bootloader confidence to HIGH.
    current = commands["efibootmgr -v"]
    commands["efibootmgr -v"] = (
        0,
        current[1] + "Boot0002* GRUB HD(1,GPT)/File(\\EFI\\arch\\grubx64.efi)\n",
        "",
    )
    # Old Sunshine shipped an agent package but its CLI is gone.
    commands["pacman -Q"] = (0, commands["pacman -Q"][1] + "sunshine-agent 0.9.1-1\n", "")


