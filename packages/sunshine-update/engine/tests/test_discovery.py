class DiscoveryTests(unittest.TestCase):
    """Verify that discovery is fully driven by root + execute."""

    def setUp(self) -> None:
        self._tmp = tempfile.TemporaryDirectory(prefix="sunshine-discovery-")
        self.root = self._tmp.name
        base_arch_root(self.root)
        self.commands = base_commands()
        self.execute = fake_executor(self.commands)
        self.addCleanup(self._tmp.cleanup)

    def assert_low_confidence_is_harmless(self, state) -> None:
        """LOW observations must never authorise destructive operations."""
        for name, observation in state.observations.items():
            if observation.confidence is Confidence.LOW:
                self.assertFalse(
                    observation.allow_destructive(),
                    f"{name} is LOW confidence but allows destructive operations",
                )

    def test_clean_arch_system(self) -> None:
        """A pristine Arch system is discovered without any Sunshine assumption."""
        state = discover(root=self.root, execute=self.execute)

        self.assertEqual(state.distribution, "arch")
        self.assertEqual(state.architecture, "x86_64")
        self.assertEqual(state.init_system, "systemd")
        self.assertEqual(state.package_manager, "pacman")

        self.assertIn("linux", state.packages)
        self.assertIn("nvidia", state.foreign_packages)  # orphan from -Qqdt
        self.assertIn("yay", state.foreign_packages)  # from -Qqm
        self.assertEqual(state.repositories, ["core", "extra", "multilib"])

        self.assertEqual(state.observations["bootloader"].detected, "grub")
        self.assertIs(state.observations["bootloader"].confidence, Confidence.MEDIUM)
        self.assertIs(state.observations["bootloader"].status, Status.CONFIGURED)

        self.assertIs(state.observations["sunshine.installation"].status, Status.ABSENT)
        self.assertNotIn("sunshine.partial-installation", state.observations)

        required = {
            "systemd",
            "pacman",
            "kernel-installation",
            "boot-entry-management",
            "desktop-session-discovery",
            "pipewire",
            "package-ownership-registry",
        }
        self.assertTrue(required <= state.capabilities)
        self.assertNotIn("configuration-ownership", state.capabilities)
        self.assertEqual(
            state.observations["packages.unknown"].detected,
            "unknown-package-ownership",
        )

        self.assert_low_confidence_is_harmless(state)
        self.assertIsInstance(state.to_dict()["capabilities"], list)

    def test_users_are_discovered_without_secret_data(self) -> None:
        """Stage B preserves user/group facts but never records password hashes."""
        state = discover(root=self.root, execute=self.execute)

        self.assertEqual([u["name"] for u in state.users], ["sunshine"])
        self.assertEqual(state.users[0]["shell"], "/bin/bash")
        self.assertEqual(state.groups["wheel"], ["sunshine"])
        self.assertTrue(state.home_directories[0]["exists"])
        self.assertIs(state.observations["users.accounts"].status, Status.FUNCTIONAL)
        self.assertIn("user-accounts", state.capabilities)

        dumped = state.to_dict()
        self.assertTrue(all("password" not in u for u in dumped["users"]))
        for observation in dumped["observations"].values():
            self.assertNotIn("shadow", str(observation).lower())

    def test_missing_user_database_is_low_confidence_not_a_crash(self) -> None:
        os.unlink(self.root + "/etc/passwd")
        state = discover(root=self.root, execute=self.execute)
        self.assertIs(state.observations["users.accounts"].status, Status.ABSENT)
        self.assertIs(state.observations["users.accounts"].confidence, Confidence.LOW)
        self.assertEqual(state.users, [])

    def test_old_sunshine_partial_installation(self) -> None:
        """Partial Sunshine markers are detected, including HIGH boot confidence."""
        add_old_sunshine(self.root, self.commands)
        state = discover(root=self.root, execute=self.execute)

        self.assertIs(state.observations["bootloader"].confidence, Confidence.HIGH)
        self.assertIs(state.observations["bootloader"].status, Status.RUNNING)

        installation = state.observations["sunshine.installation"]
        self.assertIs(installation.status, Status.CONFIGURED)
        self.assertEqual(installation.detected, "sunshine-partial-installation")
        self.assertIn("sunshine.partial-installation", state.observations)
        self.assertIs(state.observations["sunshine.component-schemas"].confidence, Confidence.HIGH)

        self.assertIn("configuration-ownership", state.capabilities)
        self.assertIn("component-schema-discovery", state.capabilities)
        self.assertIn("state-persistence", state.capabilities)
        self.assertIn("package-ownership-registry", state.capabilities)

        evidence = "\n".join(state.observations["sunshine.partial-installation"].evidence)
        self.assertIn("tools", evidence)  # missing tools are explicitly reported
        self.assert_low_confidence_is_harmless(state)

    def test_grub_package_alone_never_exceeds_medium(self) -> None:
        """A GRUB package listing cannot claim an active firmware boot entry."""
        # Remove the GRUB config and any firmware entry: only the package remains.
        os.remove(os.path.join(self.root, "boot/grub/grub.cfg"))
        state = discover(root=self.root, execute=self.execute)
        observation = state.observations["bootloader"]
        self.assertEqual(observation.detected, "grub")
        self.assertIs(observation.confidence, Confidence.MEDIUM)
        self.assertIs(observation.status, Status.INSTALLED)
        self.assertIn("package alone caps confidence at MEDIUM", "\n".join(observation.evidence))
        self.assertIs(state.observations["boot.efi"].status, Status.RUNNING)

    def test_individual_passes_accept_root_and_execute(self) -> None:
        """Each pass can be called independently with the same test doubles."""
        from core import ObservedState
        from discovery import (
            derive_capabilities,
            discover_kernel_boot,
            discover_storage,
            discover_services_desktop,
        )

        # Standalone form from the specification, both positional and keyword.
        standalone = discover_system(self.root, self.execute)
        self.assertEqual(standalone.distribution, "arch")
        standalone_kw = discover_system(root=self.root, execute=self.execute)
        self.assertEqual(standalone_kw.init_system, "systemd")

        state = ObservedState()
        discover_system(state, self.root, self.execute)
        discover_packages(state, self.root, self.execute)
        discover_kernel_boot(state, self.root, self.execute)
        discover_storage(state, self.root, self.execute)
        discover_services_desktop(state, self.root, self.execute)
        discover_sunshine(state, self.root, self.execute)
        derive_capabilities(state, self.root, self.execute)
        self.assertTrue(state.capabilities)
        self.assertEqual(state.observations["kernel.running"].evidence, ["uname -r: 6.6.1-arch1-1"])


