def write_file(root: str, path: str, content: str) -> None:
    """Write *content* to ``root + path``, creating parent directories."""
    full = Path(root) / path.lstrip("/")
    full.parent.mkdir(parents=True, exist_ok=True)
    full.write_text(content, encoding="utf-8")


def make_dir(root: str, path: str) -> None:
    """Create a directory below *root*."""
    (Path(root) / path.lstrip("/")).mkdir(parents=True, exist_ok=True)


def make_symlink(root: str, path: str, target: str) -> None:
    """Create a symlink below *root* with an unresolved target string."""
    full = Path(root) / path.lstrip("/")
    full.parent.mkdir(parents=True, exist_ok=True)
    if full.is_symlink() or full.exists():
        full.unlink()
    full.symlink_to(target)


def base_arch_root(root: str) -> None:
    """Assemble a minimal but internally consistent Arch Linux tree."""
    write_file(
        root,
        "/etc/os-release",
        'NAME="Arch Linux"\nPRETTY_NAME="Arch Linux"\nID=arch\nBUILD_ID=rolling\n',
    )
    write_file(root, "/etc/arch-release", "")
    write_file(
        root,
        "/etc/passwd",
        "root:x:0:0:root:/root:/bin/bash\n"
        "systemd-network:x:980:980:systemd Network Management:/:/usr/bin/nologin\n"
        "sunshine:x:1000:1000:Sunshine User:/home/sunshine:/bin/bash\n",
    )
    write_file(
        root,
        "/etc/group",
        "root:x:0:\n"
        "wheel:x:998:sunshine\n"
        "sudo:x:999:\n"
        "users:x:100:sunshine\n",
    )
    make_dir(root, "/home/sunshine")
    write_file(root, "/etc/pacman.conf", "[options]\nHoldPkg = pacman glibc\n[core]\n[extra]\n[multilib]\n")
    make_dir(root, "/var/lib/pacman/local")
    make_dir(root, "/var/lib/pacman/sync")
    write_file(root, "/usr/lib/systemd/systemd", "binary placeholder")
    make_dir(root, "/run/systemd/system")

    # kernels + initramfs
    make_dir(root, "/usr/lib/modules/6.6.1-arch1-1")
    make_dir(root, "/usr/lib/modules/6.6.8-arch1-1")
    write_file(root, "/usr/lib/modules/6.6.1-arch1-1/modules.order", "")
    write_file(root, "/etc/mkinitcpio.conf", "MODULES=()\nHOOKS=(base udev autodetect modconf block filesystems)\n")
    write_file(root, "/etc/mkinitcpio.d/linux.preset", "PRESETS=('default')\n")

    # EFI + ESP + GRUB config (but no GRUB boot entry by default)
    make_dir(root, "/sys/firmware/efi")
    write_file(
        root,
        "/etc/fstab",
        "# /etc/fstab\nUUID=aaaa / btrfs rw,relatime,subvol=@ 0 1\nUUID=bbbb /boot vfat rw,relatime 0 2\n",
    )
    write_file(root, "/boot/grub/grub.cfg", "# generated by grub-mkconfig\n")

    # desktop sessions and current session
    write_file(root, "/usr/share/xsessions/plasma.desktop", "[Desktop Entry]\nName=Plasma\nExec=startplasma-x11\n")
    write_file(
        root,
        "/usr/share/wayland-sessions/plasmawayland.desktop",
        "[Desktop Entry]\nName=Plasma Wayland\nExec=startplasma-wayland\n",
    )
    write_file(root, "/proc/self/environ", "XDG_SESSION_TYPE=wayland\0XDG_CURRENT_DESKTOP=KDE\0")
    make_symlink(root, "/etc/systemd/system/display-manager.service", "sddm.service")


